function Update-ScubaGwsCatalog {
    <#
    .SYNOPSIS
    Writes the policy catalog of the ScubaGoggles pack from a copy of CISA's ScubaGoggles.

    .DESCRIPTION
    Reads the Google Workspace Secure Configuration Baselines (scubagoggles/baselines/*.md) and writes catalog.json:
    the ScubaGoggles version it was built from and one entry per policy (Tests, the shape the pack index reads), with
    its requirement, criticality and the severity the pack gives it, indicators, rationale, NIST SP 800-53 and MITRE
    ATT&CK mappings and the steps to configure it. Nothing is run.

    The pack reads the catalog at run time for each result's description and remediation, which the ScubaResults
    file does not hold. A policy added in a newer version of ScubaGoggles is still reported, with the text of the
    results file only; run this again when the pack moves to a new version.

    Every .ps1 file of a pack may hold only functions, so this script is a function: dot-source the file, then call
    it. The tools folder is not one the manifest names, so the pack never loads it.

    .EXAMPLE
    git clone --depth 1 --branch v1.1.0 https://github.com/cisagov/ScubaGoggles ~/src/ScubaGoggles
    . ./tools/Update-ScubaGwsCatalog.ps1
    Update-ScubaGwsCatalog -SourcePath ~/src/ScubaGoggles
    #>
    [CmdletBinding()]
    param(
        # A clone of https://github.com/cisagov/ScubaGoggles, or the installed scubagoggles package folder (the one
        # that holds __init__.py and baselines/).
        [Parameter(Mandatory)]
        [string] $SourcePath,

        # Where to write the catalog. Defaults to catalog.json at the root of this repository.
        [string] $OutputPath = (Join-Path -Path $PSScriptRoot -ChildPath '..' -AdditionalChildPath 'catalog.json')
    )

    $ErrorActionPreference = 'Stop'

    $packageRoot = @($SourcePath, (Join-Path $SourcePath 'scubagoggles')) |
        Where-Object { Test-Path -LiteralPath (Join-Path $_ '__init__.py') } | Select-Object -First 1
    if (-not $packageRoot) { throw "No scubagoggles package (__init__.py) under $SourcePath." }
    $init = Get-Content -LiteralPath (Join-Path $packageRoot '__init__.py') -Raw
    if ($init -notmatch "__version__\s*=\s*'([^']+)'") { throw "No __version__ in $packageRoot/__init__.py." }
    $version = $Matches[1]

    $policies = foreach ($file in Get-ChildItem -LiteralPath (Join-Path $packageRoot 'baselines') -Filter '*.md' | Where-Object Name -ne 'README.md' | Sort-Object Name) {
        Read-ScubaGwsBaseline -Path $file.FullName -Version $version
    }

    $ids = @($policies | Group-Object -Property { $_.Id } | Where-Object Count -gt 1)
    if ($ids) { throw "The baselines give more than one policy the ID $($ids.Name -join ', ')." }

    $catalog = [ordered]@{
        '$comment' = 'Generated by tools/Update-ScubaGwsCatalog.ps1 from the ScubaGoggles baselines (CC0 1.0, CISA). Do not edit by hand.'
        Tool       = 'ScubaGoggles'
        Version    = $version
        Source     = 'https://github.com/cisagov/ScubaGoggles'
        Tests      = @($policies | Sort-Object { $_.Baseline }, { [int]$_.GroupNumber }, { [int]($_.ControlId -split '\.')[3].Split('v')[0] })
    }
    $catalog | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $OutputPath -Encoding utf8NoBOM
    Write-Information -InformationAction Continue -MessageData "Wrote $(@($policies).Count) policies from ScubaGoggles $version to $OutputPath."
}

function Read-ScubaGwsBaseline {
    <#
    .SYNOPSIS
    Returns one catalog entry per policy in a baseline Markdown file, such as gmail.md.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)] [string] $Path,
        [Parameter(Mandatory)] [string] $Version
    )

    $file = Get-Item -LiteralPath $Path
    $lines = @(Get-Content -LiteralPath $Path -Encoding utf8)
    $product = if ($lines[0] -match 'Baseline for (.+)$') { $Matches[1].Trim() } else { $file.BaseName }
    $group = $null
    $groupNumber = $null
    $current = $null
    # The policies of the current group, and its ### Implementation section, for groups whose steps are shared.
    $groupPolicies = [System.Collections.Generic.List[object]]::new()
    $implementation = $null
    $own = @{}
    $section = $null

    for ($i = 0; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        if ($line -match '^## (\d+)\.\s+(.+)$') {
            Complete-ScubaGwsGroup -Policy $groupPolicies -Implementation $implementation -Own $own
            $groupPolicies.Clear()
            $groupNumber = $Matches[1]; $group = $Matches[2].Trim()
            $implementation = $null; $own = @{}; $section = $null; $current = $null
            continue
        }
        if ($line -match '^## ') {
            Complete-ScubaGwsGroup -Policy $groupPolicies -Implementation $implementation -Own $own
            $groupPolicies.Clear()
            $group = $null; $implementation = $null; $own = @{}; $section = $null; $current = $null
            continue
        }
        if (-not $group) { continue }
        if ($line -match '^### Implementation') { $implementation = [System.Collections.Generic.List[string]]::new(); $section = $implementation; $current = $null; continue }
        if ($line -match '^### ') { $section = $null; $current = $null; continue }
        if ($line -match '^#### (GWS\.[A-Z]+\.\d+\.\d+v\d+)\s+[Ii]nstructions:?\s*$') {
            $own[$Matches[1]] = [System.Collections.Generic.List[string]]::new()
            $section = $own[$Matches[1]]
            continue
        }
        if ($line -match '^#### (GWS\.([A-Z]+)\.(\d+)\.(\d+))v(\d+)\s*$') {
            $controlId = $line.Substring(5).Trim()
            $id = 'MP.SCUBA.GWS.{0}.{1}.{2}' -f $Matches[2], $Matches[3], $Matches[4]
            $requirement = [System.Collections.Generic.List[string]]::new()
            $j = $i + 1
            while ($j -lt $lines.Count -and $lines[$j] -notmatch '^\s*(- _|- MITRE|####|###|\[!\[)') {
                $requirement.Add($lines[$j]); $j++
            }
            $indicators = [System.Collections.Generic.List[string]]::new()
            while ($j -lt $lines.Count -and $lines[$j] -notmatch '^\s*- ' -and $lines[$j] -notmatch '^#') {
                if ($lines[$j] -match '^\s*\[!\[([^\]]+)\]') { $indicators.Add($Matches[1]) }
                $j++
            }
            # The text of the policy, without the badge lines and the blank lines around them.
            $text = (@($requirement | Where-Object { $_ -notmatch '^\s*\[!\[' }) -join "`n").Trim()
            $criticality = if ($text -cmatch '\bSHALL\b') { 'SHALL' } elseif ($text -cmatch '\bSHOULD\b') { 'SHOULD' } elseif ($text -cmatch '\bMAY\b') { 'MAY' } else { $null }
            $current = [ordered]@{
                Id          = $id
                ControlId   = $controlId
                Product     = $product
                Baseline    = $file.BaseName
                Group       = $group
                GroupNumber = $groupNumber
                Title       = ($text -replace '\s+', ' ').Trim()
                Criticality = $criticality
                Severity    = switch ($criticality) { 'SHALL' { 'High' } 'SHOULD' { 'Medium' } 'MAY' { 'Low' } default { $null } }
                Category    = $product
                Indicators  = @($indicators | Select-Object -Unique)
                Rationale   = $null
                Note        = $null
                Nist        = @()
                Mitre       = @()
                Remediation = $null
                Url         = 'https://github.com/cisagov/ScubaGoggles/blob/v{0}/scubagoggles/baselines/{1}#{2}' -f $Version, $file.Name, ($controlId.ToLowerInvariant() -replace '[^a-z0-9]', '')
            }
            $groupPolicies.Add($current)
            $section = $null
            $i = $j - 1
            continue
        }
        if ($current -and -not $section) {
            # The baselines write both _Rationale:_ and _Rationale_:.
            if ($line -match '^\s*-\s+_Rationale(?::_|_:)\s*(.+)$') { $current.Rationale = $Matches[1].Trim() }
            elseif ($line -match '^\s*-\s+_Note(?::_|_:)\s*(.+)$') { $current.Note = $Matches[1].Trim() }
            elseif ($line -match '^\s*-\s+_NIST SP 800-53[^:_]*(?::_|_:)\s*(.+)$') { $current.Nist = @($Matches[1] -split ',\s*' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) }
            elseif ($line -match 'attack\.mitre\.org/techniques/(T\d{4})(?:/(\d{3}))?') {
                $technique = if ($Matches[2]) { "$($Matches[1]).$($Matches[2])" } else { $Matches[1] }
                $current.Mitre = @($current.Mitre) + $technique | Select-Object -Unique
            }
        }
        if ($null -ne $section) { $section.Add($line) }
    }
    Complete-ScubaGwsGroup -Policy $groupPolicies -Implementation $implementation -Own $own
}

function Complete-ScubaGwsGroup {
    <#
    .SYNOPSIS
    Gives each policy of a group its steps, and returns the policies.

    .DESCRIPTION
    A policy's own steps follow the steps its group shares, such as a Policy Group 1 Common Instructions section.
    Their headings become bold lines, so they don't outrank the headings of the Maester report.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)] [AllowEmptyCollection()] [System.Collections.Generic.List[object]] $Policy,
        [Parameter()] [AllowNull()] $Implementation,
        [Parameter(Mandatory)] [hashtable] $Own
    )

    foreach ($p in $Policy) {
        $steps = @($Implementation) + @(if ($Own.ContainsKey($p.ControlId)) { $Own[$p.ControlId] }) | Where-Object { $null -ne $_ } |
            ForEach-Object { $_ -replace '^#{3,}\s+(.+?):?\s*$', '**$1**' }
        if ($steps) { $p.Remediation = (($steps -join "`n").Trim() -replace '\n{3,}', "`n`n") }
        $p
    }
}
